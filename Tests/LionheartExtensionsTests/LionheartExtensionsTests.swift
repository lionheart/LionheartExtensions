    let dates = ["2023-03-28", "2023-03-28"]
    let formatter = try DateFormatter.formatter(dateStrings: dates)
    let validFormats = [
      "MM-dd-yyyy",
      "dd-MM-yyyy",
      "yyyy-MM-dd",
      "yyyy-dd-MM",
      "yyyyMMddHHmmssZ",
    ]
    #expect(validFormats.contains(formatter.dateFormat))
    dates.forEach { #expect(formatter.date(from: $0) != nil) }
  }
  
